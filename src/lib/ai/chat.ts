// Sprint 2 chatbot logic shared by the API route and the tests.
// The model may only use the approved FAQ, the student's synthetic profile and the matching output.
import { FAQ, FAQ_VERSION, SAMPLE_PROFILES, type FaqEntry, type MatchProfile } from "./knowledge";
import { missingProfileInfo, normalizeProfileSkills, type Recommendation } from "./matching";

export type ChatRole = "user" | "assistant";
export interface ChatMessage {
  role: ChatRole;
  content: string;
}

export type AnswerKind = "faq" | "recommendation" | "unknown";

export interface ChatReply {
  answer: string;
  /** FAQ IDs the answer is based on, plus "MATCHING" when it uses the matching engine output. */
  sources: string[];
  kind: AnswerKind;
  /** "ai": generated by the language model; "lookup": offline FAQ lookup (no model call). */
  mode: "ai" | "lookup";
  model?: string;
}

export const GROQ_MODEL = "openai/gpt-oss-120b";
/** Used when the main model hits the free tier's tokens-per-minute limit. */
export const GROQ_BACKUP_MODEL = "openai/gpt-oss-20b";
export const MAX_MESSAGES = 10;
export const MAX_MESSAGE_CHARS = 800;

export const HUMAN_CONTROL_NOTE =
  "This is a recommendation, not a placement. Eligibility is checked separately by the co-op office, and official placements are approved by people.";

export const UNKNOWN_ANSWER =
  "I don't have an approved answer for that, so I won't guess. Please contact the co-op office, and a person will answer. You can also read the FAQ page for the questions I can answer.";

export function findProfile(id: string | undefined): MatchProfile {
  return SAMPLE_PROFILES.find((p) => p.student_id === id) ?? SAMPLE_PROFILES[0]!;
}

const STOP = new Set(
  "a an the i me my am is are do does did can could to of for in on at and or if it be how what why who which when where we you your through with this that there some".split(
    " ",
  ),
);

function tokens(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, " ")
    .split(" ")
    .filter((t) => t && !STOP.has(t));
}

const RECOMMEND_WORDS = [
  "recommend",
  "recommendation",
  "recommendations",
  "suggest",
  "match",
  "matches",
  "best",
  "suit",
  "fit",
];

/** True when the question asks for internship suggestions rather than policy. */
export function isRecommendationQuestion(question: string): boolean {
  const t = tokens(question);
  return (
    t.some((w) => RECOMMEND_WORDS.some((r) => w.startsWith(r))) &&
    !/how are|how is|why/i.test(question)
  );
}

/** Offline retrieval: the FAQ entry whose question and keywords overlap most with the question.
 * Rarer words count more (a word found in one entry outweighs one found in several). */
export function retrieveFaq(question: string): { entry: FaqEntry; score: number } | null {
  const q = [...new Set(tokens(question))];
  if (q.length === 0) return null;
  const vocab = FAQ.map(
    (entry) => new Set([...tokens(entry.question), ...entry.keywords.flatMap(tokens)]),
  );
  const matches = (w: string, words: Set<string>) =>
    [...words].some(
      (k) => k === w || (w.length > 4 && k.length > 4 && (k.startsWith(w) || w.startsWith(k))),
    );
  const df = new Map(q.map((w) => [w, vocab.filter((words) => matches(w, words)).length]));
  let best: { entry: FaqEntry; score: number; weight: number } | null = null;
  FAQ.forEach((entry, i) => {
    const hit = q.filter((w) => matches(w, vocab[i]!));
    const score = hit.length / q.length;
    const weight = hit.reduce((sum, w) => sum + 1 / (df.get(w) || 1), 0);
    if (score >= 0.5 && (!best || weight > best.weight)) best = { entry, score, weight };
  });
  return best
    ? { entry: (best as { entry: FaqEntry }).entry, score: (best as { score: number }).score }
    : null;
}

export function formatRecommendations(profile: MatchProfile, recs: Recommendation[]): string {
  if (recs.length === 0) return "There are no approved listings to rank yet.";
  const lines = recs.map((r) => {
    const why = r.reasons.slice(0, 2).join("; ");
    const gap = r.gaps[0] ? ` Gap: ${r.gaps[0]}.` : "";
    return `${r.rank}. ${r.listing.title}, ${r.listing.organization_name} (${r.listing.opportunity_id}), ${r.score}% match${r.weak ? ", weak match" : ""}. ${why}.${gap}`;
  });
  return [
    `Top three for ${profile.display_name} (${profile.student_id}):`,
    ...lines,
    HUMAN_CONTROL_NOTE,
  ].join("\n");
}

/** Answer without a language model: FAQ lookup, matching output, or the human handoff. */
export function lookupReply(
  question: string,
  profile: MatchProfile,
  recs: Recommendation[],
): ChatReply {
  if (isRecommendationQuestion(question)) {
    return {
      answer: formatRecommendations(profile, recs),
      sources: ["MATCHING", "FAQ-05"],
      kind: "recommendation",
      mode: "lookup",
    };
  }
  const hit = retrieveFaq(question);
  if (hit)
    return { answer: hit.entry.answer, sources: [hit.entry.id], kind: "faq", mode: "lookup" };
  return { answer: UNKNOWN_ANSWER, sources: ["FAQ-08"], kind: "unknown", mode: "lookup" };
}

export function buildSystemPrompt(profile: MatchProfile, recs: Recommendation[]): string {
  const { skills, unmapped } = normalizeProfileSkills(profile);
  const missing = missingProfileInfo(profile);
  const faq = FAQ.map((f) => `[${f.id}] Q: ${f.question}\nA: ${f.answer}`).join("\n\n");
  const profileText = [
    `Student: ${profile.display_name} (${profile.student_id}), profile version ${profile.profile_version}, synthetic`,
    `Program: ${profile.program}`,
    `Goals: ${profile.goals}`,
    `Interests: ${profile.interests.join(", ")}`,
    `Availability: ${profile.availability ?? "not given"}`,
    `Preferred work mode: ${profile.preferred_work_mode ?? "not given"}; preferred location: ${profile.preferred_location ?? "not given"}`,
    `Skills: ${skills.map((s) => `${s.label} [${s.id}] ${s.status}${s.evidence_id ? ` (evidence ${s.evidence_id} not reviewed)` : ""}`).join("; ") || "none"}`,
    unmapped.length ? `Skills not in the shared vocabulary: ${unmapped.join(", ")}` : "",
    missing.length ? `Missing profile information: ${missing.join(", ")}` : "",
    `Eligibility status (checked by the co-op office, not by you): ${profile.eligibility_status}`,
  ]
    .filter(Boolean)
    .join("\n");
  const recText = recs
    .map(
      (r) =>
        `Rank ${r.rank}: ${r.listing.title} at ${r.listing.organization_name} (${r.listing.opportunity_id}), ${r.listing.location}, ${r.listing.work_mode}, ${r.score}% match${r.weak ? " (weak match)" : ""}. ${r.listing.origin === "sample" ? "Sample listing, not open for applications in this demo." : "Open in IPP."}\nReasons: ${r.reasons.join("; ")}\nGaps: ${r.gaps.join("; ") || "none"}`,
    )
    .join("\n\n");

  return `You are the IPP Help chatbot for a university internship practicum platform (a classroom demo with synthetic data).

Rules:
1. Answer ONLY from the APPROVED FAQ, the STUDENT PROFILE and the MATCHING OUTPUT below. Do not use outside knowledge about any university, employer, law, visa, pay, grade or deadline.
2. If the question is not covered by these sources, set kind to "unknown" and answer exactly: "${UNKNOWN_ANSWER}"
3. For internship suggestions, use only the MATCHING OUTPUT. Keep its order, titles, IDs and scores, and copy each reason and gap word for word (do not call a desirable skill required, or the reverse). Never invent listings, scores or skills.
4. Never say a student is eligible, placed, accepted or approved. Eligibility and official placements are decided by people.
5. Keep answers under 120 words, plain text, friendly and direct. Do not use markdown tables.
6. Reply with a JSON object only: {"answer": string, "sources": string[], "kind": "faq" | "recommendation" | "unknown"}. sources lists the FAQ IDs you used and "MATCHING" if you used the matching output.

APPROVED FAQ (${FAQ_VERSION}):
${faq}

STUDENT PROFILE:
${profileText}

MATCHING OUTPUT (rules-based engine; eligibility not used in ranking):
${recText || "No approved listings to rank."}`;
}

const VALID_SOURCES = new Set([...FAQ.map((f) => f.id), "MATCHING"]);

/** Server-side guard after the model call: recommendation answers always carry the human-control note. */
export function finalizeReply(reply: ChatReply): ChatReply {
  if (reply.kind === "recommendation" && !/not a placement/i.test(reply.answer)) {
    return { ...reply, answer: `${reply.answer}\n${HUMAN_CONTROL_NOTE}` };
  }
  return reply;
}

/** Validates the model's JSON; returns null when it breaks the contract so the caller can fall back. */
export function parseModelReply(content: string, model: string): ChatReply | null {
  let parsed: unknown;
  try {
    const start = content.indexOf("{");
    const end = content.lastIndexOf("}");
    parsed = JSON.parse(start >= 0 && end > start ? content.slice(start, end + 1) : content);
  } catch {
    return null;
  }
  if (!parsed || typeof parsed !== "object") return null;
  const p = parsed as { answer?: unknown; sources?: unknown; kind?: unknown };
  if (typeof p.answer !== "string" || !p.answer.trim()) return null;
  const kind: AnswerKind =
    p.kind === "faq" || p.kind === "recommendation" || p.kind === "unknown" ? p.kind : "faq";
  const sources = Array.isArray(p.sources)
    ? p.sources.filter((s): s is string => typeof s === "string" && VALID_SOURCES.has(s))
    : [];
  // An answer that claims to be grounded but cites nothing approved is treated as unknown.
  if (kind !== "unknown" && sources.length === 0) {
    return { answer: UNKNOWN_ANSWER, sources: ["FAQ-08"], kind: "unknown", mode: "ai", model };
  }
  return { answer: p.answer.trim(), sources, kind, mode: "ai", model };
}

/** Trims and bounds the conversation sent to the model. */
export function sanitizeMessages(input: unknown): ChatMessage[] {
  if (!Array.isArray(input)) return [];
  return input
    .filter(
      (m): m is ChatMessage =>
        !!m &&
        typeof m === "object" &&
        (m.role === "user" || m.role === "assistant") &&
        typeof m.content === "string",
    )
    .map((m) => ({ role: m.role, content: m.content.slice(0, MAX_MESSAGE_CHARS) }))
    .slice(-MAX_MESSAGES);
}
